def calculate_modifier(score):
	"""Расчет модификатора характеристики (D&D 5e)"""
	return (score - 10) // 2


def calculate_stats_by_rules(race, class_name):
	"""
	Расчет характеристик по правилам D&D 5e

	Args:
		race: str (например, 'Человек', 'Дварф (Холмовой)')
		class_name: str (например, 'Варвар', 'Друид')

	Returns:
		dict: {'Сила': 16, 'Ловкость': 14, ...}
	"""
	# 1. Берем базовые значения для класса
	if class_name in CLASS_BASE:
		stats = CLASS_BASE[class_name].copy()
	else:
		# Если класс не найден — используем стандартные
		stats = {'Сила': 12, 'Ловкость': 12, 'Телосложение': 12,
		         'Интеллект': 12, 'Мудрость': 12, 'Харизма': 12}
		print(f"⚠️ Класс '{class_name}' не найден в базе, используются стандартные значения")

	# 2. Добавляем бонусы за расу
	if race in RACIAL_BONUSES:
		for stat, bonus in RACIAL_BONUSES[race].items():
			if stat in stats:
				stats[stat] += bonus
	else:
		print(f"⚠️ Раса '{race}' не найдена в базе бонусов")

	# 3. Ограничиваем значения (не больше 20)
	for stat in stats:
		stats[stat] = min(20, stats[stat])

	# 4. Добавляем производные параметры
	con_mod = calculate_modifier(stats['Телосложение'])
	stats['КД'] = 10 + calculate_modifier(stats['Ловкость'])  # Базовая КД без брони
	stats['МаксХП'] = 10 + con_mod  # Примерное HP для 1 уровня

	return stats


def calculate_hp(class_name, constitution):
	"""
	Расчет ХП для 1 уровня
	"""
	hit_dice = {
		'Варвар': 12,
		'Воин': 10,
		'Паладин': 10,
		'Следопыт': 10,
		'Друид': 8,
		'Жрец': 8,
		'Маг': 6,
		'Разбойник': 8,
		'Чародей': 6,
		'Колдун': 8,
		'Монах': 8,
		'Бард': 8,
	}

	dice = hit_dice.get(class_name, 8)
	con_mod = calculate_modifier(constitution)
	return dice + con_mod


def calculate_ac(dexterity, armor_type='none'):
	"""
	Расчет Класса Доспеха (AC)
	"""
	dex_mod = calculate_modifier(dexterity)

	if armor_type == 'none':
		return 10 + dex_mod
	elif armor_type == 'light':
		return 11 + dex_mod
	elif armor_type == 'medium':
		return 13 + min(2, dex_mod)
	elif armor_type == 'heavy':
		return 18  # Примерно как латы
	else:
		return 10 + dex_mod


def compare_with_generated(generated_stats, rules_stats, race, class_name):
	"""
	Сравнение сгенерированных характеристик с рассчитанными по правилам
	"""
	print("\n" + "=" * 60)
	print("📊 СРАВНЕНИЕ ХАРАКТЕРИСТИК")
	print("=" * 60)
	print(f"Раса: {race}")
	print(f"Класс: {class_name}")
	print("-" * 60)

	# ✅ МАППИНГ КЛЮЧЕЙ (короткие имена из CSV → полные для вывода)
	KEY_MAP = {
		'Сил': 'Сила',
		'Лов': 'Ловкость',
		'Тел': 'Телосложение',
		'Инт': 'Интеллект',
		'Муд': 'Мудрость',
		'Хар': 'Харизма',
		'КД': 'КД',
		'МаксХП': 'МаксХП'
	}

	# ✅ Обратный маппинг для поиска
	REVERSE_KEY_MAP = {v: k for k, v in KEY_MAP.items()}

	stats_order = ['Сила', 'Ловкость', 'Телосложение', 'Интеллект', 'Мудрость', 'Харизма', 'КД', 'МаксХП']

	total_diff = 0
	max_diff = 0
	comparisons = {}

	for stat in stats_order:
		# ✅ Ищем значение в generated_stats по короткому ключу
		short_key = REVERSE_KEY_MAP.get(stat, stat)
		gen_val = generated_stats.get(short_key, 0)

		# ✅ Берем значение из правил
		rules_val = rules_stats.get(stat, 0)

		diff = gen_val - rules_val

		comparisons[stat] = {
			'generated': gen_val,
			'rules': rules_val,
			'diff': diff,
			'abs_diff': abs(diff)
		}

		total_diff += abs(diff)
		if abs(diff) > max_diff:
			max_diff = abs(diff)

	avg_diff = total_diff / len(stats_order)

	# Оценка
	if avg_diff <= 1.0:
		match_level = "⭐ ВЫСОКОЕ (отлично!)"
	elif avg_diff <= 2.5:
		match_level = "🟡 СРЕДНЕЕ (хорошо)"
	else:
		match_level = "🔴 НИЗКОЕ (требуется доработка)"

	# Вывод
	print(f"\n{'Параметр':<12} {'Сгенерировано':<15} {'По правилам':<15} {'Отклонение':<12}")
	print("-" * 60)

	for stat, data in comparisons.items():
		diff_str = f"{data['diff']:+d}"
		if abs(data['diff']) <= 1:
			diff_str = f"✅ {diff_str}"
		elif abs(data['diff']) <= 2:
			diff_str = f"🟡 {diff_str}"
		else:
			diff_str = f"❌ {diff_str}"

		print(f"{stat:<12} {data['generated']:>14} {data['rules']:>14} {diff_str:>12}")

	print("-" * 60)
	print(f"\n📊 Среднее отклонение: {avg_diff:.2f}")
	print(f"📊 Максимальное отклонение: {max_diff}")
	print(f"📊 Соответствие правилам: {match_level}")

	return {
		'comparisons': comparisons,
		'avg_diff': avg_diff,
		'max_diff': max_diff,
		'match_level': match_level
	}


def print_rules_stats(race, class_name):
	"""
	Вывод рассчитанных по правилам характеристик
	"""
	stats = calculate_stats_by_rules(race, class_name)

	print("\n" + "=" * 50)
	print("📖 ХАРАКТЕРИСТИКИ ПО ПРАВИЛАМ D&D 5e")
	print("=" * 50)
	print(f"Раса: {race}")
	print(f"Класс: {class_name}")
	print("-" * 50)

	# Бонусы за расу
	if race in RACIAL_BONUSES:
		print("Бонусы расы:")
		for stat, bonus in RACIAL_BONUSES[race].items():
			print(f"  {stat}: +{bonus}")

	print("\nИтоговые характеристики:")
	for stat, value in stats.items():
		mod = calculate_modifier(value)
		mod_str = f"{mod:+d}"
		print(f"  {stat}: {value} (модификатор {mod_str})")

	return stats


